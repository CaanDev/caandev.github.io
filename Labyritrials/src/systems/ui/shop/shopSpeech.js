/**
 * Получение случайной фразы из массива
 * 
 * @param {string[]} speechArray - Массив фраз
 * @returns {string} - Случайная фраза
 */
export function getRandomSpeech(speechArray) {
  return speechArray[Math.floor(Math.random() * speechArray.length)];
}

/**
 * Обновление текста речи торговца в UI
 * 
 * @param {string} text - Текст речи
 * @returns {void}
 */
export function updateShopkeeperSpeech(text) {
  const speechEl = document.getElementById('shopkeeper-speech');
  if (speechEl) {
    // Анимация смены текста
    speechEl.style.opacity = '0';
    speechEl.style.transform = 'translateY(4px)';
    
    setTimeout(() => {
      speechEl.textContent = `«${text}»`;
      speechEl.style.transition = 'all 0.3s ease';
      speechEl.style.opacity = '1';
      speechEl.style.transform = 'translateY(0)';
    }, 80);
  }
}