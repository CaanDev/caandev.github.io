/**
 * Получение записок для указанного уровня
 * 
 * @param {number} level - Номер уровня
 * @returns {NoteData[]} - Массив записок для указанного уровня
 */
export function getNotesForLevel(level) {
  return NOTES_DATA.filter(note => note.level === level);
}

/**
 * Получение записки по ID
 * 
 * @param {number} id - ID записки
 * @returns {NoteData|undefined} - Записка с указанным ID или undefined
 */
export function getNoteById(id) {
  return NOTES_DATA.find(note => note.id === id);
}

/**
 * Получение всех записок
 * 
 * @returns {NoteData[]} - Массив всех записок
 */
export function getAllNotes() {
  return NOTES_DATA;
}

/**
 * Проверка, является ли уровень босс-уровнем
 * 
 * @param {number} level - Номер уровня
 * @returns {boolean} - true, если уровень является босс-уровнем
 */
export function isBossLevel(level) {
  return level > 0 && level % 5 === 0;
}